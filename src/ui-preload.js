const { contextBridge, ipcRenderer } = require('electron');

const call = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);
const listen = (channel) => (cb) => ipcRenderer.on(channel, (_e, ...args) => cb(...args));

contextBridge.exposeInMainWorld('tide', {
  ready: call('ui:ready'),
  newTab: call('tab:new'),
  closeTab: call('tab:close'),
  selectTab: call('tab:select'),
  moveTab: call('tab:move'),
  tabMenu: call('tab:contextmenu'),
  go: call('nav:go'),
  back: call('nav:back'),
  forward: call('nav:forward'),
  reload: call('nav:reload'),
  stop: call('nav:stop'),
  home: call('nav:home'),
  openInternal: call('nav:internal'),
  openAI: call('nav:ai'),
  screenshot: call('page:screenshot'),
  mainMenu: call('menu:main'),
  muteTab: call('tab:mute'),
  resetZoom: call('zoom:reset'),
  toggleBlock: call('block:toggle'),
  bookmarkMenu: call('bookmark:menu'),
  toggleBookmark: call('bookmark:toggle'),
  passwordButton: call('pw:button'),
  siteOpen: call('site:open'),
  openReader: call('reader:open'),
  toggleTheme: call('theme:toggle'),
  omniInput: call('omni:input'),
  omniMove: call('omni:move'),
  omniEnter: call('omni:enter'),
  omniHide: call('omni:hide'),
  onOmniDone: listen('omni:done'),
  find: call('find:start'),
  stopFind: call('find:stop'),
  findVisible: call('find:visible'),
  onState: listen('state'),
  onFocusOmnibox: listen('focus-omnibox'),
  onFindOpen: listen('find-open'),
  onFindClose: listen('find-close'),
  onFindResult: listen('find-result'),
  onToast: listen('toast'),
});
